/// Audits the repository against `config_rel` and fails closed on any violation or weakened ceiling.
pub fn audit_parametric_ratchet(
    repo: &Path,
    config_rel: &Path,
) -> Result<RatchetReport, FidelityError> {
    let config_path = if config_rel.is_absolute() {
        config_rel.to_path_buf()
    } else {
        repo.join(config_rel)
    };
    let raw_cfg = std::fs::read_to_string(&config_path)
        .map_err(|e| FidelityError::Io(config_path.clone(), e))?;
    let cfg: ParametricRatchetConfig = toml::from_str(&raw_cfg)
        .map_err(|e| FidelityError::Register(format!("{}: {e}", config_path.display())))?;

    if cfg.spec != SPEC && cfg.spec != SPEC_V2 {
        return Err(FidelityError::Register(format!(
            "{}: unsupported spec {:?}, expected {:?} or {:?}",
            config_path.display(),
            cfg.spec,
            SPEC,
            SPEC_V2
        )));
    }
    if cfg.spec == SPEC_V2 && cfg.self_hosting.is_none() {
        return Err(FidelityError::Register(format!(
            "{}: spec {:?} requires a [self_hosting] ratchet section",
            config_path.display(),
            SPEC_V2
        )));
    }

    // Enforce that ceilings themselves can never be weakened above zero:
    let c = cfg.ceilings;
    if c.max_ontology_root_literal_gt_one_count != 0
        || c.max_ontology_root_string_field_count != 0
        || c.max_classical_choice_count != 0
        || c.max_ungrounded_lex_module_count != 0
        || c.max_domain_lex_magic_literal_count != 0
        || c.max_engine_rust_magic_literal_count != 0
    {
        return Err(FidelityError::Register(
            "parametric-ratchet ceilings must all remain strictly 0 (zero-constants policy)".into(),
        ));
    }
    if let Some(sh) = &cfg.self_hosting {
        if sh.max_unlifted_ui_files != 0
            || sh.max_unverified_frame_assets != 0
            || sh.max_user_required_external_accounts != 0
            || sh.max_unlifted_workspace_modules != 0
        {
            return Err(FidelityError::Register(
                "self_hosting ratchet ceilings must all remain strictly 0 (100% self-hosting policy)".into(),
            ));
        }
    }

    let mut violations: Vec<RatchetViolation> = Vec::new();

    // 1. Audit ontology_root (`Foundation/Ontology/V1/Model.lex.tex`):
    let ont_full = repo.join(&cfg.ontology_root);
    let ont_src =
        std::fs::read_to_string(&ont_full).map_err(|e| FidelityError::Io(ont_full.clone(), e))?;
    let ont_lits = scan_lex_magic_literals(&ont_src);
    for (line, tok) in &ont_lits {
        violations.push(RatchetViolation {
            path: cfg.ontology_root.clone(),
            line: *line,
            detail: format!("ontology root literal outside {{0, 1}}: `{tok}`"),
        });
    }
    let mut ontology_root_string_field_count = 0usize;
    for (idx, line) in ont_src.lines().enumerate() {
        if line.contains("type: String") || line.contains("type: (List String)") {
            ontology_root_string_field_count += 1;
            violations.push(RatchetViolation {
                path: cfg.ontology_root.clone(),
                line: idx + 1,
                detail: "ontology root contains forbidden String field".into(),
            });
        }
    }

    // 2. Walk every `.lex.tex` file under `app/src/`:
    let app_src = repo.join("app/src");
    let mut lex_files = Vec::new();
    collect_files_with_suffix(&app_src, ".lex.tex", &mut lex_files)?;
    lex_files.sort();

    let mut grounded_map: BTreeMap<String, u8> = BTreeMap::new();
    for entry in &cfg.stratum_modules {
        if entry.role.trim().is_empty() {
            return Err(FidelityError::Register(format!(
                "stratum_module `{}` has an empty role",
                entry.path
            )));
        }
        if entry.stratum > MAX_STRATUM_RANK {
            return Err(FidelityError::Register(format!(
                "stratum_module `{}` has stratum {} > {}",
                entry.path, entry.stratum, MAX_STRATUM_RANK
            )));
        }
        if grounded_map
            .insert(entry.path.clone(), entry.stratum)
            .is_some()
        {
            return Err(FidelityError::Register(format!(
                "duplicate stratum_module `{}`",
                entry.path
            )));
        }
    }

    let mut disk_lex_paths = BTreeSet::new();
    let mut classical_choice_count = 0usize;
    let mut ungrounded_lex_module_count = 0usize;

    for full in &lex_files {
        let rel = rel_slash(repo, full);
        disk_lex_paths.insert(rel.clone());
        if !grounded_map.contains_key(&rel) {
            ungrounded_lex_module_count += 1;
            violations.push(RatchetViolation {
                path: rel.clone(),
                line: 0,
                detail: "LexLean module is not grounded in model/parametric-ratchet.toml".into(),
            });
        }
        let text = std::fs::read_to_string(full).map_err(|e| FidelityError::Io(full.clone(), e))?;
        for (idx, line) in text.lines().enumerate() {
            if line.contains("Classical.choice") {
                classical_choice_count += 1;
                violations.push(RatchetViolation {
                    path: rel.clone(),
                    line: idx + 1,
                    detail: "forbidden non-constructive `Classical.choice` axiom".into(),
                });
            }
        }
    }

    for declared in grounded_map.keys() {
        if !disk_lex_paths.contains(declared) {
            ungrounded_lex_module_count += 1;
            violations.push(RatchetViolation {
                path: declared.clone(),
                line: 0,
                detail: "declared stratum_module does not exist on disk".into(),
            });
        }
    }

    // 3. Audit `pure_zero_one_lex_modules` for zero literals `> 1`:
    let mut domain_lex_magic_literal_count = 0usize;
    for mod_rel in &cfg.pure_zero_one_lex_modules {
        let mod_full = repo.join(mod_rel);
        let src = std::fs::read_to_string(&mod_full)
            .map_err(|e| FidelityError::Io(mod_full.clone(), e))?;
        let found = scan_lex_magic_literals(&src);
        domain_lex_magic_literal_count += found.len();
        for (line, tok) in found {
            violations.push(RatchetViolation {
                path: mod_rel.clone(),
                line,
                detail: format!("domain LexLean literal outside {{0, 1}}: `{tok}`"),
            });
        }
    }

    // 4. Audit shipped Rust engine sources across `engine_rust_root` and `additional_rust_roots`:
    let mut rust_files = Vec::new();
    let mut all_roots = vec![cfg.engine_rust_root.clone()];
    all_roots.extend(cfg.additional_rust_roots.iter().cloned());
    for root_rel in &all_roots {
        let rust_root = repo.join(root_rel);
        let before = rust_files.len();
        collect_files_with_suffix(&rust_root, ".rs", &mut rust_files)?;
        if rust_files.len() == before {
            return Err(FidelityError::Register(format!(
                "rust source root `{root_rel}` contains no `.rs` files"
            )));
        }
    }
    rust_files.sort_by_key(|p| rel_slash(repo, p));
    rust_files.dedup();

    let mut engine_rust_magic_literal_count = 0usize;
    for full in &rust_files {
        let rel = rel_slash(repo, full);
        let src = std::fs::read_to_string(full).map_err(|e| FidelityError::Io(full.clone(), e))?;
        let found = scan_rust_magic_literals(&src);
        engine_rust_magic_literal_count += found.len();
        for (line, tok) in found {
            violations.push(RatchetViolation {
                path: rel.clone(),
                line,
                detail: format!("magic numeric literal `{tok}` in shipped engine source"),
            });
        }
    }

    // 5. Audit tightened Self-Hosting Ratchet (`prism/parametric-ratchet/2`):
    let mut unlifted_ui_file_count = 0usize;
    let mut unverified_frame_asset_count = 0usize;
    let mut user_required_external_account_count = 0usize;
    let mut unlifted_workspace_module_count = 0usize;
    let mut self_hosted_lifted_module_count = 0usize;
    let mut blank_frame_total_bytes = 0usize;
    let mut blank_frame_max_bytes = 0usize;

    if let Some(sh) = &cfg.self_hosting {
        blank_frame_max_bytes = sh.max_blank_frame_bytes;
        let frame_dir = repo.join(&sh.blank_frame_dir);
        let mut frame_files = Vec::new();
        collect_all_files(&frame_dir, &mut frame_files)?;
        frame_files.sort();
        let allowed_frame: BTreeSet<String> =
            sh.allowed_blank_frame_files.iter().cloned().collect();
        let mut seen_frame = BTreeSet::new();
        for full in &frame_files {
            let rel_in_frame = full
                .strip_prefix(&frame_dir)
                .unwrap_or(full)
                .to_string_lossy()
                .replace('\\', "/");
            let bytes = std::fs::read(full).map_err(|e| FidelityError::Io(full.clone(), e))?;
            blank_frame_total_bytes = blank_frame_total_bytes.saturating_add(bytes.len());
            if !allowed_frame.contains(&rel_in_frame) {
                unverified_frame_asset_count += 1;
                violations.push(RatchetViolation {
                    path: rel_slash(repo, full),
                    line: 0,
                    detail: format!(
                        "unverified loose asset `{rel_in_frame}` in Blank Frame `{}`",
                        sh.blank_frame_dir
                    ),
                });
            }
            seen_frame.insert(rel_in_frame);
            if let Ok(text) = std::str::from_utf8(&bytes) {
                let lower = text.to_ascii_lowercase();
                for forbidden in [
                    "oauth2/authorize",
                    "accounts.google.com/o/oauth2",
                    "github.com/login/oauth",
                    "sign in with github",
                ] {
                    if lower.contains(forbidden) {
                        user_required_external_account_count += 1;
                        violations.push(RatchetViolation {
                            path: rel_slash(repo, full),
                            line: 0,
                            detail: format!(
                                "forbidden external account / OAuth wall `{forbidden}` in Blank Frame"
                            ),
                        });
                    }
                }
            }
        }
        for req_name in &allowed_frame {
            if !seen_frame.contains(req_name) {
                unverified_frame_asset_count += 1;
                violations.push(RatchetViolation {
                    path: format!("{}/{req_name}", sh.blank_frame_dir),
                    line: 0,
                    detail: "missing required immutable Blank Frame asset".into(),
                });
            }
        }
        if blank_frame_total_bytes > sh.max_blank_frame_bytes {
            unverified_frame_asset_count += 1;
            violations.push(RatchetViolation {
                path: sh.blank_frame_dir.clone(),
                line: 0,
                detail: format!(
                    "Blank Frame exceeds byte budget: {} B > {} B",
                    blank_frame_total_bytes, sh.max_blank_frame_bytes
                ),
            });
        }

        // Verify View Immutability Seal exists on disk:
        let seal_full = repo.join(&sh.immutability_seal);
        let seal_text = std::fs::read_to_string(&seal_full)
            .map_err(|e| FidelityError::Io(seal_full.clone(), e))?;

        // Parse Verdant's self-emitted ratchet manifest and cryptographically verify every module:
        let manifest_full = repo.join(&sh.ratchet_manifest);
        let manifest_raw = std::fs::read_to_string(&manifest_full)
            .map_err(|e| FidelityError::Io(manifest_full.clone(), e))?;
        let manifest: SelfHostRatchetManifest = toml::from_str(&manifest_raw)
            .map_err(|e| FidelityError::Register(format!("{}: {e}", manifest_full.display())))?;

        if manifest.spec != SELF_HOST_MANIFEST_SPEC {
            violations.push(RatchetViolation {
                path: sh.ratchet_manifest.clone(),
                line: 0,
                detail: format!(
                    "unexpected manifest spec {:?}, expected {:?}",
                    manifest.spec, SELF_HOST_MANIFEST_SPEC
                ),
            });
        }
        if manifest.generator != SELF_HOST_MANIFEST_GENERATOR {
            violations.push(RatchetViolation {
                path: sh.ratchet_manifest.clone(),
                line: 0,
                detail: format!(
                    "manifest must be generated by Verdant ({:?}), found {:?}",
                    SELF_HOST_MANIFEST_GENERATOR, manifest.generator
                ),
            });
        }
        if manifest.unlifted_ui_files != 0
            || manifest.unverified_frame_assets != 0
            || manifest.user_required_external_accounts != 0
            || manifest.unlifted_workspace_modules != 0
        {
            unlifted_workspace_module_count += manifest.unlifted_workspace_modules;
            unlifted_ui_file_count += manifest.unlifted_ui_files;
            unverified_frame_asset_count += manifest.unverified_frame_assets;
            user_required_external_account_count += manifest.user_required_external_accounts;
            violations.push(RatchetViolation {
                path: sh.ratchet_manifest.clone(),
                line: 0,
                detail: "self-host ratchet manifest reports non-zero unlifted/unverified counters"
                    .into(),
            });
        }
        for (label, digest) in [
            ("source_commit_kappa", &manifest.source_commit_kappa),
            ("source_tree_root_sha256", &manifest.source_tree_root_sha256),
            (
                "immutability_seal_root_sha256",
                &manifest.immutability_seal_root_sha256,
            ),
            ("release_capsule_sha256", &manifest.release_capsule_sha256),
        ] {
            if !is_hex_sha256(digest) {
                violations.push(RatchetViolation {
                    path: sh.ratchet_manifest.clone(),
                    line: 0,
                    detail: format!("invalid 64-char hex SHA-256 for `{label}`"),
                });
            }
        }
        let expected_seal_needle = format!(
            "\"sealRootSha256Hex\": \"{}\"",
            manifest.immutability_seal_root_sha256
        );
        if !seal_text.contains(&expected_seal_needle) {
            unlifted_ui_file_count += 1;
            violations.push(RatchetViolation {
                path: sh.immutability_seal.clone(),
                line: 0,
                detail: "immutability-seal.json root SHA-256 does not match self-host-ratchet-manifest.toml (re-run `verdant operator ratchet-lift`)".into(),
            });
        }

        let mut manifest_map: BTreeMap<String, String> = BTreeMap::new();
        for rec in &manifest.lifted_modules {
            if !is_hex_sha256(&rec.sha256) {
                violations.push(RatchetViolation {
                    path: rec.path.clone(),
                    line: 0,
                    detail: "invalid 64-char SHA-256 digest in self-host-ratchet-manifest.toml"
                        .into(),
                });
            }
            if manifest_map
                .insert(rec.path.clone(), rec.sha256.clone())
                .is_some()
            {
                violations.push(RatchetViolation {
                    path: rec.path.clone(),
                    line: 0,
                    detail: "duplicate lifted_module entry in self-host-ratchet-manifest.toml"
                        .into(),
                });
            }
        }

        // Verify EVERY shipped Rust `.rs` file is lifted into VerdantVcs at its exact live SHA-256:
        for full in &rust_files {
            let rel = rel_slash(repo, full);
            let bytes = std::fs::read(full).map_err(|e| FidelityError::Io(full.clone(), e))?;
            let live = crate::hex(&Sha256::digest(&bytes));
            match manifest_map.get(&rel) {
                Some(expected) if expected == &live => {
                    self_hosted_lifted_module_count += 1;
                }
                Some(_) => {
                    unlifted_workspace_module_count += 1;
                    violations.push(RatchetViolation {
                        path: rel,
                        line: 0,
                        detail: "Rust module modified outside Verdant ratchet-lift (SHA-256 mismatch; run `verdant operator ratchet-lift`)".into(),
                    });
                }
                None => {
                    unlifted_workspace_module_count += 1;
                    violations.push(RatchetViolation {
                        path: rel,
                        line: 0,
                        detail: "Rust module is not lifted in self-host-ratchet-manifest.toml"
                            .into(),
                    });
                }
            }
        }

        // Verify EVERY Prism `.lex.tex` stratum is lifted into VerdantVcs at its exact live SHA-256:
        for full in &lex_files {
            let rel = rel_slash(repo, full);
            let bytes = std::fs::read(full).map_err(|e| FidelityError::Io(full.clone(), e))?;
            let live = crate::hex(&Sha256::digest(&bytes));
            match manifest_map.get(&rel) {
                Some(expected) if expected == &live => {
                    self_hosted_lifted_module_count += 1;
                }
                Some(_) => {
                    unlifted_workspace_module_count += 1;
                    violations.push(RatchetViolation {
                        path: rel,
                        line: 0,
                        detail: "LexLean module modified outside Verdant ratchet-lift (SHA-256 mismatch; run `verdant operator ratchet-lift`)".into(),
                    });
                }
                None => {
                    unlifted_workspace_module_count += 1;
                    violations.push(RatchetViolation {
                        path: rel,
                        line: 0,
                        detail: "LexLean module is not lifted in self-host-ratchet-manifest.toml"
                            .into(),
                    });
                }
            }
        }

        // Verify EVERY canonical Viewpoint UI HTML file is lifted at its exact live SHA-256:
        for vp_rel in &sh.lifted_viewpoint_files {
            let full = repo.join(vp_rel);
            let bytes = std::fs::read(&full).map_err(|e| FidelityError::Io(full.clone(), e))?;
            let live = crate::hex(&Sha256::digest(&bytes));
            match manifest_map.get(vp_rel) {
                Some(expected) if expected == &live => {
                    self_hosted_lifted_module_count += 1;
                }
                Some(_) => {
                    unlifted_ui_file_count += 1;
                    violations.push(RatchetViolation {
                        path: vp_rel.clone(),
                        line: 0,
                        detail: "UI Viewpoint modified outside Verdant ratchet-lift (SHA-256 mismatch; run `verdant operator ratchet-lift`)".into(),
                    });
                }
                None => {
                    unlifted_ui_file_count += 1;
                    violations.push(RatchetViolation {
                        path: vp_rel.clone(),
                        line: 0,
                        detail: "UI Viewpoint is not lifted in self-host-ratchet-manifest.toml"
                            .into(),
                    });
                }
            }
        }
    }

    // 6. Audit shrink-only hand-written Rust surface ratchet (`frontier.toml`, VE-53):
    let mut frontier_total_functions = 0usize;
    let mut frontier_lifted_functions = 0usize;
    let mut frontier_residue_functions = 0usize;
    let mut frontier_uncertified_functions = 0usize;
    if let Some(fr) = &cfg.frontier_ratchet {
        let frontier_full = repo.join(&fr.frontier_register);
        let frontier_raw = std::fs::read_to_string(&frontier_full)
            .map_err(|e| FidelityError::Io(frontier_full.clone(), e))?;
        let parsed: UorustFrontierFile = toml::from_str(&frontier_raw)
            .map_err(|e| FidelityError::Register(format!("{}: {e}", frontier_full.display())))?;
        if parsed.spec != UORUST_FRONTIER_SPEC {
            violations.push(RatchetViolation {
                path: fr.frontier_register.clone(),
                line: 0,
                detail: format!(
                    "unexpected frontier spec {:?}, expected {:?}",
                    parsed.spec, UORUST_FRONTIER_SPEC
                ),
            });
        }
        let lift = parsed.lift;
        let expected_sum = lift
            .lifted
            .saturating_add(lift.residue)
            .saturating_add(lift.foreign)
            .saturating_add(lift.effect);
        if lift.functions != expected_sum
            || parsed.lifted.len() != lift.lifted
            || parsed.residue.len() != lift.residue
            || parsed.foreign.len() != lift.foreign
            || parsed.effect.len() != lift.effect
        {
            violations.push(RatchetViolation {
                path: fr.frontier_register.clone(),
                line: 0,
                detail: format!(
                    "frontier [lift] header counts disagree with table rows (functions={}, sum={}, rows={}/{}/{}/{})",
                    lift.functions,
                    expected_sum,
                    parsed.lifted.len(),
                    parsed.residue.len(),
                    parsed.foreign.len(),
                    parsed.effect.len()
                ),
            });
        }
        frontier_total_functions = lift.functions;
        frontier_lifted_functions = lift.lifted;
        frontier_residue_functions = lift.residue;
        frontier_uncertified_functions = lift
            .residue
            .saturating_add(lift.foreign)
            .saturating_add(lift.effect);
        if frontier_lifted_functions < fr.min_lifted_functions {
            violations.push(RatchetViolation {
                path: fr.frontier_register.clone(),
                line: 0,
                detail: format!(
                    "uorust lifted functions regressed: {} < floor {}",
                    frontier_lifted_functions, fr.min_lifted_functions
                ),
            });
        }
        if frontier_residue_functions > fr.max_residue_functions {
            violations.push(RatchetViolation {
                path: fr.frontier_register.clone(),
                line: 0,
                detail: format!(
                    "hand-written Rust residue grew: {} > ceiling {}",
                    frontier_residue_functions, fr.max_residue_functions
                ),
            });
        }
        if frontier_uncertified_functions > fr.max_uncertified_functions {
            violations.push(RatchetViolation {
                path: fr.frontier_register.clone(),
                line: 0,
                detail: format!(
                    "uncertified Rust surface grew: {} > ceiling {}",
                    frontier_uncertified_functions, fr.max_uncertified_functions
                ),
            });
        }
        if let Some(expected_tree_sha) = &fr.frontier_rust_tree_sha256 {
            let trimmed_sha = expected_tree_sha.trim();
            if !trimmed_sha.is_empty() {
                let mut tree_hasher = Sha256::new();
                for full in &rust_files {
                    let rel = rel_slash(repo, full);
                    let bytes =
                        std::fs::read(full).map_err(|e| FidelityError::Io(full.clone(), e))?;
                    tree_hasher.update(rel.as_bytes());
                    tree_hasher.update([0_u8]);
                    tree_hasher.update(&bytes);
                    tree_hasher.update([0_u8]);
                }
                let live_tree_sha = crate::hex(&tree_hasher.finalize());
                if trimmed_sha != live_tree_sha {
                    violations.push(RatchetViolation {
                        path: fr.frontier_register.clone(),
                        line: 0,
                        detail: format!(
                            "frontier.toml is stale against live Rust source tree (recorded {} != live {}; run `npm run ratchet`)",
                            &trimmed_sha[..16.min(trimmed_sha.len())],
                            &live_tree_sha[..16]
                        ),
                    });
                }
            }
        }
    }

    // 7. Audit Surface High-Water-Mark Ratchet (`[surface_ratchet]`, VE-55):
    let mut observed_wasm_core_bytes = 0usize;
    let mut observed_wasm_uorc_bytes = 0usize;
    let mut observed_release_capsule_bytes = 0usize;
    let mut observed_max_rust_file_lines = 0usize;
    let mut observed_max_js_file_lines = 0usize;
    if let Some(sr) = &cfg.surface_ratchet {
        let core_full = repo.join(&sr.wasm_core_path);
        observed_wasm_core_bytes = std::fs::metadata(&core_full)
            .map_err(|e| FidelityError::Io(core_full.clone(), e))?
            .len() as usize;
        if observed_wasm_core_bytes > sr.max_wasm_core_bytes {
            violations.push(RatchetViolation {
                path: sr.wasm_core_path.clone(),
                line: 0,
                detail: format!(
                    "core Wasm grew past ratchet watermark: {} B > {} B",
                    observed_wasm_core_bytes, sr.max_wasm_core_bytes
                ),
            });
        }

        let uorc_full = repo.join(&sr.wasm_uorc_path);
        observed_wasm_uorc_bytes = std::fs::metadata(&uorc_full)
            .map_err(|e| FidelityError::Io(uorc_full.clone(), e))?
            .len() as usize;
        if observed_wasm_uorc_bytes > sr.max_wasm_uorc_bytes {
            violations.push(RatchetViolation {
                path: sr.wasm_uorc_path.clone(),
                line: 0,
                detail: format!(
                    "UORC Wasm grew past ratchet watermark: {} B > {} B",
                    observed_wasm_uorc_bytes, sr.max_wasm_uorc_bytes
                ),
            });
        }

        let pin_full = repo.join(&sr.frame_pin_path);
        let pin_raw = std::fs::read_to_string(&pin_full)
            .map_err(|e| FidelityError::Io(pin_full.clone(), e))?;
        for line in pin_raw.lines() {
            let trimmed = line.trim();
            if let Some(rest) = trimmed.strip_prefix("\"capsuleByteLen\":") {
                if let Ok(v) = rest.trim().trim_end_matches(',').parse::<usize>() {
                    observed_release_capsule_bytes = v;
                    break;
                }
            }
        }
        if observed_release_capsule_bytes == 0 {
            violations.push(RatchetViolation {
                path: sr.frame_pin_path.clone(),
                line: 0,
                detail: "frame-pin.json missing capsuleByteLen".into(),
            });
        } else if observed_release_capsule_bytes > sr.max_release_capsule_bytes {
            violations.push(RatchetViolation {
                path: sr.frame_pin_path.clone(),
                line: 0,
                detail: format!(
                    "release .holo capsule grew past ratchet watermark: {} B > {} B",
                    observed_release_capsule_bytes, sr.max_release_capsule_bytes
                ),
            });
        }

        let excl_rs: BTreeSet<String> = sr.rust_line_exclude.iter().cloned().collect();
        for full in &rust_files {
            let rel = rel_slash(repo, full);
            if excl_rs.contains(&rel) {
                continue;
            }
            let text =
                std::fs::read_to_string(full).map_err(|e| FidelityError::Io(full.clone(), e))?;
            let lines = text.lines().count();
            if lines > observed_max_rust_file_lines {
                observed_max_rust_file_lines = lines;
            }
            if lines > sr.max_handwritten_rust_file_lines {
                violations.push(RatchetViolation {
                    path: rel,
                    line: 0,
                    detail: format!(
                        "hand-written Rust file grew past god-file ratchet: {lines} lines > {} lines (extract a submodule)",
                        sr.max_handwritten_rust_file_lines
                    ),
                });
            }
        }

        let mut js_files = Vec::new();
        for js_root in &sr.js_surface_roots {
            let full_root = repo.join(js_root);
            collect_files_with_suffix(&full_root, ".mjs", &mut js_files)?;
            collect_files_with_suffix(&full_root, ".js", &mut js_files)?;
        }
        js_files.sort();
        js_files.dedup();
        for full in &js_files {
            let rel = rel_slash(repo, full);
            if sr
                .js_line_exclude_prefixes
                .iter()
                .any(|p| rel.starts_with(p))
            {
                continue;
            }
            let text =
                std::fs::read_to_string(full).map_err(|e| FidelityError::Io(full.clone(), e))?;
            let lines = text.lines().count();
            if lines > observed_max_js_file_lines {
                observed_max_js_file_lines = lines;
            }
            if lines > sr.max_js_file_lines {
                violations.push(RatchetViolation {
                    path: rel,
                    line: 0,
                    detail: format!(
                        "JS file grew past god-file ratchet: {lines} lines > {} lines (extract a module)",
                        sr.max_js_file_lines
                    ),
                });
            }
        }
    }

    let report = RatchetReport {
        ontology_root_literal_gt_one_count: ont_lits.len(),
        ontology_root_string_field_count,
        classical_choice_count,
        ungrounded_lex_module_count,
        domain_lex_magic_literal_count,
        engine_rust_magic_literal_count,
        grounded_lex_module_count: disk_lex_paths.len(),
        audited_rust_file_count: rust_files.len(),
        unlifted_ui_file_count,
        unverified_frame_asset_count,
        user_required_external_account_count,
        unlifted_workspace_module_count,
        self_hosted_lifted_module_count,
        blank_frame_total_bytes,
        blank_frame_max_bytes,
        frontier_total_functions,
        frontier_lifted_functions,
        frontier_residue_functions,
        frontier_uncertified_functions,
        observed_wasm_core_bytes,
        observed_wasm_uorc_bytes,
        observed_release_capsule_bytes,
        observed_max_rust_file_lines,
        observed_max_js_file_lines,
    };

    if report.ontology_root_literal_gt_one_count > c.max_ontology_root_literal_gt_one_count
        || report.ontology_root_string_field_count > c.max_ontology_root_string_field_count
        || report.classical_choice_count > c.max_classical_choice_count
        || report.ungrounded_lex_module_count > c.max_ungrounded_lex_module_count
        || report.domain_lex_magic_literal_count > c.max_domain_lex_magic_literal_count
        || report.engine_rust_magic_literal_count > c.max_engine_rust_magic_literal_count
        || report.unlifted_ui_file_count > 0
        || report.unverified_frame_asset_count > 0
        || report.user_required_external_account_count > 0
        || report.unlifted_workspace_module_count > 0
        || !violations.is_empty()
    {
        let mut msg = String::from("zero-constants & self-hosting parametric ratchet refused:\n");
        for v in violations.iter().take(16) {
            if v.line > 0 {
                msg.push_str(&format!("  - {}:{}: {}\n", v.path, v.line, v.detail));
            } else {
                msg.push_str(&format!("  - {}: {}\n", v.path, v.detail));
            }
        }
        return Err(FidelityError::False(msg.trim_end().to_string()));
    }

    Ok(report)
}

fn is_hex_sha256(s: &str) -> bool {
    s.len() == 64 && s.bytes().all(|b| b.is_ascii_hexdigit())
}

fn collect_all_files(dir: &Path, out: &mut Vec<PathBuf>) -> Result<(), FidelityError> {
    let entries = std::fs::read_dir(dir).map_err(|e| FidelityError::Io(dir.to_path_buf(), e))?;
    for entry in entries {
        let entry = entry.map_err(|e| FidelityError::Io(dir.to_path_buf(), e))?;
        let path = entry.path();
        if path.is_dir() {
            collect_all_files(&path, out)?;
        } else if path.is_file() {
            out.push(path);
        }
    }
    Ok(())
}

fn rel_slash(repo: &Path, full: &Path) -> String {
    full.strip_prefix(repo)
        .unwrap_or(full)
        .to_string_lossy()
        .replace('\\', "/")
}

fn collect_files_with_suffix(
    dir: &Path,
    suffix: &str,
    out: &mut Vec<PathBuf>,
) -> Result<(), FidelityError> {
    let entries = std::fs::read_dir(dir).map_err(|e| FidelityError::Io(dir.to_path_buf(), e))?;
    for entry in entries {
        let entry = entry.map_err(|e| FidelityError::Io(dir.to_path_buf(), e))?;
        let path = entry.path();
        if path.is_dir() {
            collect_files_with_suffix(&path, suffix, out)?;
        } else if path
            .file_name()
            .and_then(|n| n.to_str())
            .is_some_and(|n| n.ends_with(suffix))
        {
            out.push(path);
        }
    }
    Ok(())
}

/// Scans `\begin{semanticmodule}...\end{semanticmodule}` of a LexLean source and returns
/// `(line_number, token)` for every numeric literal outside `{"0", "1"}`.
pub fn scan_lex_magic_literals(source: &str) -> Vec<(usize, String)> {
    let open_tag = "\\begin{semanticmodule}";
    let close_tag = "\\end{semanticmodule}";
    let Some(start_idx) = source.find(open_tag) else {
        return Vec::new();
    };
    let body_start = start_idx + open_tag.len();
    let body_end = source[body_start..]
        .find(close_tag)
        .map_or(source.len(), |off| body_start + off);

    let mut sanitized = vec![b' '; source.len()];
    for (idx, &b) in source.as_bytes().iter().enumerate() {
        if b == b'\n' {
            sanitized[idx] = b'\n';
        } else if idx >= body_start && idx < body_end {
            sanitized[idx] = b;
        }
    }

    // Blank out `"..."` string literals inside `semanticmodule`:
    let mut i = body_start;
    while i < body_end {
        if sanitized[i] == b'"' {
            sanitized[i] = b' ';
            i += 1;
            while i < body_end {
                let c = sanitized[i];
                if c == b'\\' && i + 1 < body_end {
                    if sanitized[i] != b'\n' {
                        sanitized[i] = b' ';
                    }
                    if sanitized[i + 1] != b'\n' {
                        sanitized[i + 1] = b' ';
                    }
                    i += 2;
                    continue;
                }
                if c != b'\n' {
                    sanitized[i] = b' ';
                }
                i += 1;
                if c == b'"' {
                    break;
                }
            }
            continue;
        }
        i += 1;
    }

    let mut out = Vec::new();
    let mut line = 1usize;
    let mut pos = 0usize;
    while pos < sanitized.len() {
        let c = sanitized[pos];
        if c == b'\n' {
            line += 1;
            pos += 1;
            continue;
        }
        if c.is_ascii_alphabetic() || c == b'_' {
            while pos < sanitized.len()
                && (sanitized[pos].is_ascii_alphanumeric() || sanitized[pos] == b'_')
            {
                pos += 1;
            }
            continue;
        }
        if c.is_ascii_digit() {
            let start = pos;
            while pos < sanitized.len()
                && (sanitized[pos].is_ascii_alphanumeric() || sanitized[pos] == b'_')
            {
                pos += 1;
            }
            let tok = String::from_utf8_lossy(&sanitized[start..pos]).into_owned();
            if tok != "0" && tok != "1" {
                out.push((line, tok));
            }
            continue;
        }
        pos += 1;
    }
    out
}

/// Scans a shipped Rust source file (excluding comments, string/char literals, and `#[cfg(test)]`
/// items) and returns `(line_number, token)` for every float literal outside `{0.0, 1.0}` and
/// every integer literal `> 1`.
pub fn scan_rust_magic_literals(source: &str) -> Vec<(usize, String)> {
    let mut buf = strip_rust_comments_and_strings(source.as_bytes());
    blank_cfg_test_items(&mut buf);

    let mut out = Vec::new();
    let mut line = 1usize;
    let mut i = 0usize;
    while i < buf.len() {
        let c = buf[i];
        if c == b'\n' {
            line += 1;
            i += 1;
            continue;
        }
        if c.is_ascii_alphabetic() || c == b'_' {
            while i < buf.len() && (buf[i].is_ascii_alphanumeric() || buf[i] == b'_') {
                i += 1;
            }
            continue;
        }
        if c.is_ascii_digit() {
            let start = i;
            let is_radix = c == b'0'
                && i + 1 < buf.len()
                && matches!(buf[i + 1], b'x' | b'X' | b'b' | b'B' | b'o' | b'O');
            if is_radix {
                i += 2;
                while i < buf.len() && (buf[i].is_ascii_alphanumeric() || buf[i] == b'_') {
                    i += 1;
                }
                let tok = String::from_utf8_lossy(&buf[start..i]).into_owned();
                if !is_allowed_radix_zero_or_one(&tok) {
                    out.push((line, tok));
                }
                continue;
            }

            while i < buf.len() && (buf[i].is_ascii_digit() || buf[i] == b'_') {
                i += 1;
            }
            let mut is_float = false;
            if i + 1 < buf.len() && buf[i] == b'.' && buf[i + 1].is_ascii_digit() {
                is_float = true;
                i += 1;
                while i < buf.len() && (buf[i].is_ascii_digit() || buf[i] == b'_') {
                    i += 1;
                }
            }
            if i < buf.len() && (buf[i] == b'e' || buf[i] == b'E') {
                let next_ok = i + 1 < buf.len()
                    && (buf[i + 1].is_ascii_digit() || buf[i + 1] == b'+' || buf[i + 1] == b'-');
                if next_ok {
                    is_float = true;
                    i += 1;
                    if i < buf.len() && (buf[i] == b'+' || buf[i] == b'-') {
                        i += 1;
                    }
                    while i < buf.len() && (buf[i].is_ascii_digit() || buf[i] == b'_') {
                        i += 1;
                    }
                }
            }
            // Optional Rust numeric suffix (`_u64`, `f64`, `usize`, ...):
            while i < buf.len() && (buf[i].is_ascii_alphanumeric() || buf[i] == b'_') {
                i += 1;
            }
            let tok = String::from_utf8_lossy(&buf[start..i]).into_owned();
            let stem: String = strip_numeric_suffix(&tok)
                .chars()
                .filter(|&c| c != '_')
                .collect();
            if is_float {
                if stem != "0.0" && stem != "1.0" {
                    out.push((line, tok));
                }
            } else if stem != "0" && stem != "1" {
                out.push((line, tok));
            }
            continue;
        }
        i += 1;
    }
    out
}

const INT_OR_FLOAT_SUFFIXES: &[&str] = &[
    "u128", "i128", "usize", "isize", "u64", "i64", "u32", "i32", "u16", "i16", "u8", "i8", "f64",
    "f32",
];

fn strip_numeric_suffix(raw: &str) -> &str {
    for suf in INT_OR_FLOAT_SUFFIXES {
        if let Some(stem) = raw.strip_suffix(suf) {
            return stem.trim_end_matches('_');
        }
    }
    raw
}

fn is_allowed_radix_zero_or_one(tok: &str) -> bool {
    let stem = strip_numeric_suffix(tok);
    if stem.len() < 3 {
        return false;
    }
    let radix = match stem.as_bytes()[1] {
        b'x' | b'X' => 16,
        b'b' | b'B' => 2,
        b'o' | b'O' => 8,
        _ => return false,
    };
    let digits: String = stem[2..].chars().filter(|&c| c != '_').collect();
    u128::from_str_radix(&digits, radix).is_ok_and(|v| v <= 1)
}

fn strip_rust_comments_and_strings(bytes: &[u8]) -> Vec<u8> {
    let skip_quoted = |quote_at: usize| -> usize {
        let mut j = quote_at + 1;
        while j < bytes.len() {
            if bytes[j] == b'\\' {
                j += 2;
                continue;
            }
            if bytes[j] == b'"' {
                return j + 1;
            }
            j += 1;
        }
        bytes.len()
    };
    let skip_raw = |start: usize| -> Option<usize> {
        let mut j = start;
        if j < bytes.len() && bytes[j] == b'b' {
            j += 1;
        }
        if j >= bytes.len() || bytes[j] != b'r' {
            return None;
        }
        if start > 0 && (bytes[start - 1].is_ascii_alphanumeric() || bytes[start - 1] == b'_') {
            return None;
        }
        j += 1;
        let mut hashes = 0usize;
        while j < bytes.len() && bytes[j] == b'#' {
            hashes += 1;
            j += 1;
        }
        if j >= bytes.len() || bytes[j] != b'"' {
            return None;
        }
        j += 1;
        while j < bytes.len() {
            if bytes[j] == b'"'
                && j + hashes < bytes.len()
                && bytes[j + 1..=j + hashes].iter().all(|&b| b == b'#')
            {
                return Some(j + 1 + hashes);
            }
            j += 1;
        }
        Some(bytes.len())
    };
    let skip_char = |quote_at: usize| -> Option<usize> {
        let k = quote_at + 1;
        if k >= bytes.len() {
            return None;
        }
        if bytes[k] == b'\\' {
            let mut j = k + 2;
            while j < bytes.len() && j <= k + 10 {
                if bytes[j] == b'\'' {
                    return Some(j + 1);
                }
                if bytes[j] == b'\n' {
                    return None;
                }
                j += 1;
            }
            return None;
        }
        let rest = std::str::from_utf8(&bytes[k..]).ok()?;
        let ch = rest.chars().next()?;
        let close = k + ch.len_utf8();
        if close < bytes.len() && bytes[close] == b'\'' {
            Some(close + 1)
        } else {
            None
        }
    };

    let mut out = vec![b' '; bytes.len()];
    for (idx, &b) in bytes.iter().enumerate() {
        if b == b'\n' {
            out[idx] = b'\n';
        }
    }

    let mut i = 0usize;
    while i < bytes.len() {
        if i + 1 < bytes.len() && bytes[i] == b'/' && bytes[i + 1] == b'/' {
            while i < bytes.len() && bytes[i] != b'\n' {
                i += 1;
            }
            continue;
        }
        if i + 1 < bytes.len() && bytes[i] == b'/' && bytes[i + 1] == b'*' {
            let mut depth = 1usize;
            i += 2;
            while i < bytes.len() && depth > 0 {
                if i + 1 < bytes.len() && bytes[i] == b'/' && bytes[i + 1] == b'*' {
                    depth += 1;
                    i += 2;
                } else if i + 1 < bytes.len() && bytes[i] == b'*' && bytes[i + 1] == b'/' {
                    depth -= 1;
                    i += 2;
                } else {
                    i += 1;
                }
            }
            continue;
        }
        if let Some(after_raw) = skip_raw(i) {
            i = after_raw;
            continue;
        }
        if i + 1 < bytes.len() && bytes[i] == b'b' && bytes[i + 1] == b'"' {
            i = skip_quoted(i + 1);
            continue;
        }
        if bytes[i] == b'"' {
            i = skip_quoted(i);
            continue;
        }
        if i + 1 < bytes.len() && bytes[i] == b'b' && bytes[i + 1] == b'\'' {
            if let Some(after_ch) = skip_char(i + 1) {
                i = after_ch;
                continue;
            }
        }
        if bytes[i] == b'\'' {
            if let Some(after_ch) = skip_char(i) {
                i = after_ch;
                continue;
            }
        }

        out[i] = bytes[i];
        i += 1;
    }
    out
}

fn blank_cfg_test_items(buf: &mut [u8]) {
    let needle = b"#[cfg(test)]";
    let mut i = 0usize;
    while i + needle.len() <= buf.len() {
        if &buf[i..i + needle.len()] == needle {
            let attr_start = i;
            let mut j = i + needle.len();
            while j < buf.len() && buf[j] != b'{' && buf[j] != b';' {
                j += 1;
            }
            let end = if j < buf.len() && buf[j] == b'{' {
                let mut depth = 1usize;
                let mut k = j + 1;
                while k < buf.len() && depth > 0 {
                    if buf[k] == b'{' {
                        depth += 1;
                    } else if buf[k] == b'}' {
                        depth -= 1;
                    }
                    k += 1;
                }
                k
            } else {
                (j + 1).min(buf.len())
            };
            for slot in &mut buf[attr_start..end] {
                if *slot != b'\n' {
                    *slot = b' ';
                }
            }
            i = end;
            continue;
        }
        i += 1;
    }
}

