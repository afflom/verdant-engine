const MAX_STRATUM_RANK: u8 = 7;

/// Parsed configuration from `model/parametric-ratchet.toml`.
#[derive(Clone, Debug, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct ParametricRatchetConfig {
    /// Format identifier (`prism/parametric-ratchet/1` or `prism/parametric-ratchet/2`).
    pub spec: String,
    /// Relative path to `Foundation/Ontology/V1/Model.lex.tex`.
    pub ontology_root: String,
    /// Relative directory of shipped Rust engine sources (`crates/verdant-core/src`).
    pub engine_rust_root: String,
    /// Additional shipped Rust crate source roots permanently audited for zero magic literals.
    #[serde(default)]
    pub additional_rust_roots: Vec<String>,
    /// LexLean modules whose `semanticmodule` body must contain zero numeric literals `> 1`.
    pub pure_zero_one_lex_modules: Vec<String>,
    /// Hard zero ceilings enforced by the ratchet.
    pub ceilings: RatchetCeilings,
    /// Tightened self-hosting & Stitch-only ratchet configuration (required for `prism/parametric-ratchet/2`).
    #[serde(default)]
    pub self_hosting: Option<SelfHostingRatchetConfig>,
    /// Shrink-only hand-written Rust surface ratchet backed by `uorust` `frontier.toml` (`VE-53`).
    #[serde(default)]
    pub frontier_ratchet: Option<FrontierRatchetConfig>,
    /// Monotonic high-water-mark ratchet for Wasm size, `.holo` capsule weight, and max file LOC (`VE-55`).
    #[serde(default)]
    pub surface_ratchet: Option<SurfaceRatchetConfig>,
    /// Complete mapping of every `app/src/**/*.lex.tex` module to its causal Stratum `0..=7`.
    #[serde(rename = "stratum_module")]
    pub stratum_modules: Vec<StratumModuleEntry>,
}

