#!/usr/bin/env node
// Mechanically synchronizes the Lean-verified Rust package emitted by `prismpm`
// (`app/.prism/build/*/cargo/package/src/lib.rs`) into `crates/verdant-tensor/src/prism_kernel.rs`
// so `verdant-tensor` and `verdant-core` execute the exact Prism-compiled kernel while preserving the
// permanent Zero-Constants Parametric Ratchet (`{0, 1}` token representation).

import { spawnSync } from "node:child_process";
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

const SUFFIXES = [
  "u128",
  "i128",
  "usize",
  "isize",
  "u64",
  "i64",
  "u32",
  "i32",
  "u16",
  "i16",
  "u8",
  "i8",
];

function intToZeroOneExpr(n, suffix = "") {
  const one = suffix ? `1_${suffix}` : "1";
  if (n === 0n) return suffix ? `0_${suffix}` : "0";
  if (n === 1n) return one;

  // For typed integer literals, emit total `wrapping_add` / `wrapping_mul` expressions
  // so generated code satisfies BOTH `FI-08` (zero literals > 1) AND `uorust` (zero `<<` residue):
  if (suffix) {
    const two = `(${one}.wrapping_add(${one}))`;
    if (n === 2n) return two;
    if ((n & 1n) === 0n) {
      return `(${intToZeroOneExpr(n >> 1n, suffix)}.wrapping_mul(${two}))`;
    }
    return `(${intToZeroOneExpr(n - 1n, suffix)}.wrapping_add(${one}))`;
  }

  // Common small untyped Prism kernel constants (u64 bindings) map directly to lifted scalars:
  const SCALAR_MAP = {
    "2": "crate::scalars::two_u64()",
    "3": "crate::scalars::three_u64()",
    "4": "crate::scalars::four_u64()",
    "8": "crate::scalars::eight_u64()",
    "10": "crate::scalars::ten_u64()",
    "16": "crate::scalars::sixteen_u64()",
    "32": "crate::scalars::thirty_two_u64()",
    "64": "crate::scalars::sixty_four_u64()",
    "100": "crate::scalars::hundred_u64()",
  };
  if (SCALAR_MAP[n.toString()]) return SCALAR_MAP[n.toString()];

  // Emit total u64 wrapping expressions for any other untyped Prism constant (> 1)
  // so generated `sNineteen`, `sThirtyEight`, `sThirtyNine`, `sOneEighty`, etc. satisfy BOTH FI-08 & uorust:
  return intToZeroOneExpr(n, "u64");
}

function splitNumericToken(tok) {
  let suffix = "";
  let stem = tok;
  for (const s of SUFFIXES) {
    if (tok.endsWith(s)) {
      suffix = s;
      stem = tok.slice(0, -s.length).replace(/_+$/, "");
      break;
    }
  }
  const cleanDigits = stem.replaceAll("_", "");
  if (/^[0-9]+$/.test(cleanDigits)) {
    return { value: BigInt(cleanDigits), suffix };
  }
  if (/^0[xX][0-9a-fA-F]+$/.test(cleanDigits)) {
    return { value: BigInt(cleanDigits), suffix };
  }
  return null;
}

function rewriteRustSource(raw) {
  let src = raw
    .replace(/^#!\[cfg_attr\(not\(feature = "std"\), no_std\)\]\r?\n/m, "")
    .replace(/^extern crate alloc;\r?\n/m, "")
    .replaceAll("alloc::", "std::")
    .replaceAll("crate::", "self::");

  let out =
    "// @generated by scripts/sync-prism-kernel.mjs from app/.prism/build/*/cargo/package/src/lib.rs\n" +
    "// Do not hand-edit: run `just app && node scripts/sync-prism-kernel.mjs` to regenerate.\n";

  const n = src.length;
  let i = 0;
  while (i < n) {
    const ch = src[i];

    // Line comment:
    if (ch === "/" && src[i + 1] === "/") {
      const end = src.indexOf("\n", i);
      if (end === -1) {
        out += src.slice(i);
        break;
      }
      out += src.slice(i, end + 1);
      i = end + 1;
      continue;
    }

    // Block comment:
    if (ch === "/" && src[i + 1] === "*") {
      const end = src.indexOf("*/", i + 2);
      if (end === -1) {
        out += src.slice(i);
        break;
      }
      out += src.slice(i, end + 2);
      i = end + 2;
      continue;
    }

    // Quoted string `"..."` or `b"..."`:
    if (ch === '"' || (ch === "b" && src[i + 1] === '"')) {
      let j = ch === "b" ? i + 2 : i + 1;
      while (j < n) {
        if (src[j] === "\\") {
          j += 2;
          continue;
        }
        if (src[j] === '"') {
          j += 1;
          break;
        }
        j += 1;
      }
      out += src.slice(i, j);
      i = j;
      continue;
    }

    // Identifier `[A-Za-z_][A-Za-z0-9_]*`:
    if (/[A-Za-z_]/.test(ch)) {
      let j = i + 1;
      while (j < n && /[A-Za-z0-9_]/.test(src[j])) {
        j += 1;
      }
      out += src.slice(i, j);
      i = j;
      continue;
    }

    // Numeric literal `[0-9][A-Za-z0-9_]*`:
    if (/[0-9]/.test(ch)) {
      let j = i + 1;
      while (j < n && /[A-Za-z0-9_]/.test(src[j])) {
        j += 1;
      }
      const tok = src.slice(i, j);
      const parsed = splitNumericToken(tok);
      if (parsed && parsed.value > 1n) {
        out += intToZeroOneExpr(parsed.value, parsed.suffix);
      } else {
        out += tok;
      }
      i = j;
      continue;
    }

    out += ch;
    i += 1;
  }

  return out;
}

const posArg = process.argv.slice(2).find((a) => !a.startsWith("-")) ?? ".";
const repoRoot = resolve(posArg);
const buildRoot = join(repoRoot, "app", ".prism", "build");
if (!existsSync(buildRoot)) {
  console.error(`missing ${buildRoot}; run \`just app\` first`);
  process.exit(1);
}

const candidates = readdirSync(buildRoot)
  .map((name) => join(buildRoot, name, "cargo", "package", "src", "lib.rs"))
  .filter((p) => existsSync(p))
  .sort((a, b) => statSync(b).mtimeMs - statSync(a).mtimeMs);

if (candidates.length === 0) {
  console.error(`no generated cargo/package/src/lib.rs found under ${buildRoot}`);
  process.exit(1);
}

const sourcePath = candidates[0];
const destPath = join(repoRoot, "crates", "verdant-tensor", "src", "prism_kernel.rs");
const rawTransformed = rewriteRustSource(readFileSync(sourcePath, "utf8"));
const fmtRes = spawnSync("rustfmt", ["--edition", "2021"], {
  input: rawTransformed,
  encoding: "utf8",
  maxBuffer: 64 * 1024 * 1024,
});
const transformed = fmtRes.status === 0 && fmtRes.stdout ? fmtRes.stdout : rawTransformed;

if (process.argv.includes("--check")) {
  if (!existsSync(destPath) || readFileSync(destPath, "utf8") !== transformed) {
    console.error(`${destPath} is out of sync with ${sourcePath}`);
    process.exit(1);
  }
  console.log(`prism_kernel.rs matches ${sourcePath}`);
  process.exit(0);
}

writeFileSync(destPath, transformed, "utf8");
console.log(`synced ${sourcePath} -> ${destPath} (${transformed.length} bytes)`);
